// Merges a lazily-loaded feature chunk (js/i18n-chunks/*.js's { en, ro }
// exports) into the live dictionary. Idempotent/safe to call more than once
// for the same chunk (e.g. a module reachable from two different trigger
// points, both racing to load it) — Object.assign just overwrites each
// namespace with the same data again.
//
// Runs the same key-parity check this app's dictionary always relied on
// manual review to hold (see CLAUDE.md) — but automated now, since the
// dictionary is no longer one file a reviewer can eyeball end to end in one
// sitting. A mismatch is logged loudly (console.error, every affected key)
// rather than thrown: t()'s own English-fallback safety net already keeps
// a missing key from ever showing broken UI to a real user, so this stays
// a diagnostic, not a crash — same "degrade gracefully, never hard-fail on
// a translation gap" posture as t() itself.
export function registerDictionary({ en, ro }) {
  checkNamespaceParity(en, ro);
  Object.assign(dict.en, en);
  Object.assign(dict.ro, ro);
}

function leafKeySet(obj, prefix = "") {
  const keys = new Set();
  for (const [k, v] of Object.entries(obj || {})) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object") for (const nested of leafKeySet(v, path)) keys.add(nested);
    else keys.add(path);
  }
  return keys;
}

function checkNamespaceParity(en, ro) {
  const enKeys = leafKeySet(en);
  const roKeys = leafKeySet(ro);
  const onlyEn = [...enKeys].filter((k) => !roKeys.has(k));
  const onlyRo = [...roKeys].filter((k) => !enKeys.has(k));
  if (onlyEn.length || onlyRo.length) {
    console.error(
      `[i18n] en/ro key-parity mismatch in a registered dictionary chunk. ` +
        (onlyEn.length ? `Missing from ro: ${onlyEn.join(", ")}. ` : "") +
        (onlyRo.length ? `Missing from en: ${onlyRo.join(", ")}.` : "")
    );
  }
}

// Runs the same check against the always-loaded core dictionary itself at
// module-eval time, so a core-namespace parity break is caught on every
// single boot (dev or prod), not just whenever someone happens to open the
// one feature whose chunk drifted.
checkNamespaceParity(dict.en, dict.ro);

function detectDefaultLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "ro") return stored;
  return (navigator.language || "").toLowerCase().startsWith("ro") ? "ro" : "en";
}

let currentLang = detectDefaultLang();
const listeners = new Set();

function lookup(lang, key) {
  return key.split(".").reduce((node, part) => (node && typeof node === "object" ? node[part] : undefined), dict[lang]);
}

export function t(key, vars) {
  let value = lookup(currentLang, key);
  if (value === undefined) value = lookup("en", key); // safety net, should never be needed
  if (value === undefined) return key;
  if (vars) {
    for (const [name, val] of Object.entries(vars)) {
      value = value.replace(new RegExp(`{{${name}}}`, "g"), String(val));
    }
  }
  return value;
}

export function getLanguage() {
  return currentLang;
}

export function getLocale() {
  return currentLang === "ro" ? "ro-RO" : "en-US";
}

export function setLanguage(lang) {
  if (lang !== "en" && lang !== "ro") return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  applyStaticTranslations();
  listeners.forEach((fn) => fn(lang));
}

export function onLanguageChange(fn) {
  listeners.add(fn);
}

// Applies translations to every element in the DOM carrying a data-i18n*
// attribute. Static markup (labels, headings, placeholders, aria-labels) is
// annotated declaratively in index.html; anything computed at runtime
// (toasts, dynamic sheet titles, log item text) is translated at its own
// call site via t() instead, since it isn't present in the DOM up front.
export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  });
}

export function initI18n() {
  document.documentElement.lang = currentLang;
  applyStaticTranslations();
}
